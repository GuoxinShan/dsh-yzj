import { chromium } from 'playwright'
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1560, height: 1000 }, locale: 'zh-CN' })
await page.goto('http://127.0.0.1:3080/', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(6000)
await page.getByTestId('yzj-dock-home').click().catch(() => {})
await page.waitForTimeout(2000)
await page.getByTestId('yzj-workbench-tabs').getByRole('tab', { name: '推进' }).click()
await page.waitForTimeout(4500)
const before = await page.getByTestId('yzj-advance-pane').innerText()
console.log('BEFORE:', /尚未巡检|上次巡检/.test(before) ? (before.match(/上次巡检[^\n]*/) ?? ['尚未巡检'])[0] : '尚未巡检')
await page.getByTestId('yzj-advance-patrol-now').click()
await page.waitForTimeout(15000)
const after = await page.getByTestId('yzj-advance-pane').innerText()
const line = (after.match(/上次巡检[^\n]*/) ?? ['无'])[0]
console.log('AFTER:', line)
console.log(/上次巡检/.test(after) ? 'PASS 机械巡检落 scanLine' : 'FAIL scanLine 未更新')
await page.screenshot({ path: '/Users/guoxinshan/dev/dsh-yzj/.acceptance/shots-advance-ux/patrol-mech.png' })
await browser.close()
